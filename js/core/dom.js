/**
 * @file Utilitários de DOM: escape contextual para HTML, seleção e delegação de eventos.
 * Toda string dinâmica interpolada em template HTML deve passar por `esc()`.
 */

const ESCAPE_MAP = Object.freeze({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;', '`': '&#96;',
});

/**
 * Escapa texto para inserção segura em HTML (conteúdo e atributos entre aspas duplas).
 * @param {unknown} value
 * @returns {string}
 */
export const esc = (value) => String(value ?? '').replace(/[&<>"'`]/g, (ch) => ESCAPE_MAP[ch]);

/**
 * Atalho para querySelector com erro explícito quando o elemento é obrigatório.
 * @param {string} selector
 * @param {ParentNode} [root=document]
 * @returns {HTMLElement}
 */
export const qs = (selector, root = document) => {
  const el = root.querySelector(selector);
  if (!el) throw new Error(`Elemento não encontrado: ${selector}`);
  return /** @type {HTMLElement} */ (el);
};

/**
 * Registra um handler delegado para elementos com `data-action`.
 * @param {HTMLElement} root Contêiner que recebe o listener.
 * @param {string} eventName Ex.: 'click', 'change', 'input'.
 * @param {Object<string, function(HTMLElement, Event): void>} handlers Mapa ação → handler.
 * @returns {function(): void} Função para remover o listener.
 */
export const delegate = (root, eventName, handlers) => {
  /** @param {Event} event */
  const listener = (event) => {
    const target = /** @type {HTMLElement} */ (event.target);
    const el = target.closest?.('[data-action]');
    if (!el || !root.contains(el)) return;
    const handler = handlers[el.dataset.action];
    if (handler) handler(/** @type {HTMLElement} */ (el), event);
  };
  root.addEventListener(eventName, listener);
  return () => root.removeEventListener(eventName, listener);
};

